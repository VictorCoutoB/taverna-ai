export const dictionaries: Record<Language, Dict> = { pt, en };
export type TKey = keyof Dict;

export function useT() {
  const lang = useSettings((s) => s.settings.language);
  return (key: TKey) => dictionaries[lang][key];
}

export function errorMessage(lang: Language, e: unknown): string {
  const kind = (e as { kind?: string })?.kind;
  const key = `error_${kind ?? 'unknown'}` as TKey;
  const base = dictionaries[lang][key] ?? dictionaries[lang].error_unknown;
  const detail = (e as Error)?.message;
  return kind && kind !== 'unknown' ? base : `${base}${detail ? `\n${detail.slice(0, 200)}` : ''}`;
}
